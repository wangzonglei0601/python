if response.status_code == 200:
    print("页面原始编码:", response.encoding)
    # 核心修复：直接用response.text，requests自动解压gzip，不用手动decode content
    text = response.text
    with open('baidu5.html', 'w', encoding="utf-8") as f:
        f.write(text)
    print("页面保存完成！")
else:
    print("请求失败，状态码：", response.status_code)